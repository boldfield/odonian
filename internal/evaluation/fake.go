// FakeAdapterMode controls how the fake adapter behaves.
type FakeAdapterMode string

const (
	FakeModeSuccess       FakeAdapterMode = "success"
	FakeModeMalformed     FakeAdapterMode = "malformed"
	FakeModeUnsupported   FakeAdapterMode = "unsupported"
	FakeModeInterrupted   FakeAdapterMode = "interrupted"
	FakeModeExecutionFail FakeAdapterMode = "failed"
)

// FakeAdapterConfig configures the fake adapter's behavior.
type FakeAdapterConfig struct {
	Mode               FakeAdapterMode
	CandidateName      string
	ModelID            string
	RuntimeVersion     string
	PromptVersion      string
	FindingCount       int
	ErrorMessage       string
	ResponseDelay      time.Duration
	MalformedReason    string
	ReasoningSettings  map[string]interface{}
	GenerationSettings map[string]interface{}
	ToolConfiguration  []ToolConfig
}

// ExecuteFakeAdapter runs the fake adapter with the given mode.
// In a real scenario, this would be called via the registered executable.
// It respects the request's ResultPath field and writes there instead of the supplied resultPath.
func ExecuteFakeAdapter(requestPath, resultPath string, cfg FakeAdapterConfig) error {
	startTime := time.Now()

	// Read the request to validate it.
	requestData, err := os.ReadFile(requestPath)
	if err != nil {
		return fmt.Errorf("read request: %w", err)
	}

	var req CandidateRequest
	if err := json.Unmarshal(requestData, &req); err != nil {
		return fmt.Errorf("unmarshal request: %w", err)
	}

	// Validate the request
	if err := req.Validate(); err != nil {
		return fmt.Errorf("invalid request: %w", err)
	}

	// Use the request's ResultPath
	actualResultPath := req.ResultPath

	// Simulate processing delay.
	if cfg.ResponseDelay > 0 {
		time.Sleep(cfg.ResponseDelay)
	}

	// Generate response based on mode.
	var responseData []byte
	var err2 error

	switch cfg.Mode {
	case FakeModeSuccess:
		response := generateSuccessResponse(req, startTime, cfg)
		if err := response.Validate(); err != nil {
			return fmt.Errorf("invalid success response: %w", err)
		}
		responseData, err2 = json.MarshalIndent(response, "", "  ")
	case FakeModeMalformed:
		// For malformed mode, emit genuinely invalid JSON
		responseData = []byte("{ invalid json that won't parse }")
		err2 = nil
	case FakeModeUnsupported:
		response := generateUnsupportedResponse(req, startTime, cfg)
		if err := response.Validate(); err != nil {
			return fmt.Errorf("invalid unsupported response: %w", err)
		}
		responseData, err2 = json.MarshalIndent(response, "", "  ")
	case FakeModeInterrupted:
		response := generateInterruptedResponse(req, startTime, cfg)
		if err := response.Validate(); err != nil {
			return fmt.Errorf("invalid interrupted response: %w", err)
		}
		responseData, err2 = json.MarshalIndent(response, "", "  ")
	case FakeModeExecutionFail:
		response := generateFailedResponse(req, startTime, cfg)
		if err := response.Validate(); err != nil {
			return fmt.Errorf("invalid failed response: %w", err)
		}
		responseData, err2 = json.MarshalIndent(response, "", "  ")
	default:
		return fmt.Errorf("unknown fake adapter mode: %s", cfg.Mode)
	}

	if err2 != nil {
		return fmt.Errorf("marshal response: %w", err2)
	}

	if err := os.MkdirAll(filepath.Dir(actualResultPath), 0755); err != nil {
		return fmt.Errorf("create result directory: %w", err)
	}

	if err := os.WriteFile(actualResultPath, responseData, 0644); err != nil {
		return fmt.Errorf("write result: %w", err)
	}

	return nil
}

func generateSuccessResponse(req CandidateRequest, startTime time.Time, cfg FakeAdapterConfig) CandidateResponse {
	endTime := time.Now()
	duration := endTime.Sub(startTime)

	findings := []Finding{}
	for i := 0; i < cfg.FindingCount; i++ {
		severity := "minor"
		if i == 0 {
			severity = "major"
		}
		findings = append(findings, Finding{
			Severity: severity,
			Category: "correctness",
			Summary:  fmt.Sprintf("Finding %d: test issue", i+1),
			Details:  fmt.Sprintf("This is a test finding %d generated by the fake adapter", i+1),
			File:     "example.go",
			Line:     ptrInt(10 + i*5),
		})
	}

	identity := CandidateIdentity{
		AdapterName:        cfg.CandidateName,
		AdapterVersion:     "1.0",
		ModelID:            cfg.ModelID,
		RuntimeName:        "fake_runtime",
		RuntimeVersion:     cfg.RuntimeVersion,
		PromptVersion:      cfg.PromptVersion,
		AccountOrPool:      "fake_pool",
		ReasoningSettings:  cfg.ReasoningSettings,
		GenerationSettings: cfg.GenerationSettings,
		ToolConfiguration:  cfg.ToolConfiguration,
	}

	return CandidateResponse{
		Version:            AdapterVersion,
		Status:             StatusCompleted,
		Findings:           findings,
		ReviewCompleted:    true,
		EffectiveCandidate: identity,
		Timing: ResponseTiming{
			StartedAt:   startTime,
			CompletedAt: endTime,
			Duration:    duration,
		},
		Usage: &ResponseUsage{
			Units: "fake_units",
		},
	}
}

